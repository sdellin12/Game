"""Count-only planning checks for proposed cards; not a match simulator."""
import argparse
import itertools
import json
from pathlib import Path

SOURCE=Path(__file__).resolve().parents[2]/'design/packages/discard_draw.json'


def load_package():
    package=json.loads(SOURCE.read_text(encoding='utf-8'))
    cards=package['cards']
    if package['status']!='design-proposal' or len({c['key'] for c in cards})!=len(cards):raise ValueError('Invalid proposal identity')
    for card in cards:
        if (card['kind']!='action' or card['color']!='Generic' or any(type(card[k]) is not int or card[k]<0 for k in ('cost','draw','discard_before_draw'))
                or type(card['conditional_on_discard']) is not bool or card['discard_before_draw'] not in (0,1)
                or card['conditional_on_discard']!=bool(card['discard_before_draw'])):raise ValueError('Unsupported proposal grammar')
    return package


def plan(card,hand=5,available=5,deck=20,*,lantern=False,battery=False,archive=False):
    if any(type(x) is not int or x<0 for x in (hand,available,deck)) or hand<1 or any(type(x) is not bool for x in (lantern,battery,archive)):raise ValueError('Invalid planning inputs')
    result={'card':card['key'],'hand_before':hand,'available_before':available,'deck_before':deck,
            'lantern':lantern,'battery':battery,'archive':archive}
    if available<card['cost']:return dict(result,status='cannot_pay',hand_after=hand,available_after=available)
    remaining=hand-1  # The played Action is publicly pending, never discard fodder.
    discarded=min(card['discard_before_draw'],remaining)
    draw=card['draw'] if not card['conditional_on_discard'] or discarded==card['discard_before_draw'] else 0
    actual=min(draw,deck)
    remaining=remaining-discarded+actual
    if actual<draw:
        return dict(result,status='engine_draw_continuation_required',drawn=actual,draw_remaining=draw-actual,
                    hand_during_effect=remaining,available_during_effect=available-card['cost'],captured_draws=actual,captured_discards=discarded)
    overflow=max(0,remaining-7)
    after_effect=available-card['cost']+int(lantern)*actual+int(battery)*discarded
    return dict(result,status='resolved',drawn=actual,discarded_during_effect=discarded,end_discards=overflow,
                hand_before_end=remaining,hand_after=remaining-overflow,net_hand=remaining-overflow-hand,
                available_after_effect=after_effect,available_after=after_effect+int(battery)*overflow,
                net_resources=-card['cost']+int(lantern)*actual+int(battery)*(discarded+overflow),
                permanent_capacity_gained=int(archive)*(discarded+overflow))


def evaluate(package):
    counts={}
    for card in package['cards']:
        for hand,available,deck,flags in itertools.product(range(1,11),range(11),range(5),itertools.product((False,True),repeat=3)):
            row=plan(card,hand,available,deck,lantern=flags[0],battery=flags[1],archive=flags[2])
            counts[row['status']]=counts.get(row['status'],0)+1
            if row['status']=='resolved':
                assert 0<=row['hand_after']<=7 and row['available_after']>=0
                assert row['hand_after']==hand-1-row['discarded_during_effect']+row['drawn']-row['end_discards']
            elif row['status']=='cannot_pay':
                assert row['hand_after']==hand and row['available_after']==available
            else:
                assert row['draw_remaining']>0 and 'available_after' not in row
    examples=[]
    for card in package['cards']:
        for engines in (False,True):examples.append(plan(card,lantern=engines,battery=engines,archive=engines))
    return {'package_id':package['package_id'],'version':package['version'],'cases':sum(counts.values()),'statuses':counts,'examples':examples}


def markdown(package,report):
    lines=['# Discard/draw package economy checks','','Generated by `python -m crucible_play.package_economy --format markdown`. Edit the JSON proposal or generator, then regenerate.','',
           'Source: design/packages/discard_draw.json. Proposal scope and timing: ../DISCARD_DRAW_PACKAGE.md.','',
           f"Checked {report['cases']} count-only cases: "+', '.join(f'{k}: {v}' for k,v in report['statuses'].items())+'.','',
           '## Proposed cards','', '| Card | Cost | Type / color | Rules |','| --- | --- | --- | --- |']
    for c in package['cards']:lines.append(f"| {c['name']} | {c['cost']} | Action / Generic | {c['rules_text']} |")
    lines+=['','## Five-card hand, five resources, twenty-card deck','',
            'Assume all optional rewards are accepted, all required draws complete, and no plays occur between effect completion and End cleanup. All-engines means one Lantern, Battery and Well already in play; their setup costs are excluded.','',
            '| Card | Engines | Hand after End | Resource change | Capacity gained |','| --- | --- | --- | --- | --- |']
    names={c['key']:c['name'] for c in package['cards']}
    for r in report['examples']:lines.append(f"| {names[r['card']]} | {'All three' if r['lantern'] else 'None'} | {r['hand_after']} | {r['net_resources']:+} | {r['permanent_capacity_gained']} |")
    lines+=['','Capacity waits for a future refill. Positive resource change is a refund after effect completion, not permission to cast without the full upfront cost. Short-deck cases stop at engine continuation; they do not predict refill acceptance, elimination, subsequent rewards or a final hand.','']
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--format',choices=('json','markdown'),default='json')
    args=parser.parse_args();package=load_package();report=evaluate(package)
    if args.format=='markdown':print(markdown(package,report),end='')
    else:print(json.dumps(report,indent=2))
    return 0


if __name__=='__main__':raise SystemExit(main())
