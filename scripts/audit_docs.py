def documents(root=ROOT):
    paths=[root/'README.md',root/'Game_Lore.md',root/'tests/fixtures/README.md']
    paths+=list((root/'docs').rglob('*.md'))
    paths+=list((root/'references').rglob('README.md'))
    return sorted({p for p in paths if p.is_file()})


def role(path):
    if path in CURRENT:return 'Current guide',CURRENT[path]
    if path in HISTORY:return 'Archive','Historical record; not current instructions'
    if path in PLANS:return 'Plan/specification','Read status banner; future scope is not implemented scope'
    if path.startswith('references/'):return 'External reference intake','Reference-only; never automatic Crucible rules'
    if path.endswith('/DOCUMENTATION_INDEX.md'):return 'Generated index','Generated by scripts/audit_docs.py'
    if path.rsplit('/',1)[-1] in GENERATED:return 'Generated experiment table','Use the named generator; retain historical inputs'
    return 'Experiment evidence','Checkpoint-specific results; PROJECT_STATE.md owns current status'


def headings(text):
    result=set();counts={};fenced=False
    for line in text.splitlines():
        if line.lstrip().startswith(('```','~~~')):fenced=not fenced
        if fenced:continue
        match=re.match(r'^#{1,6}\s+(.+?)\s*#*$',line)
        if match:
            slug=re.sub(r'[^\w\- ]','',match[1].lower()).replace(' ','-')
            n=counts.get(slug,0);counts[slug]=n+1
            result.add(slug+(f'-{n}' if n else ''))
    return result


def broken_links(root=ROOT):
    errors=[]
    for path in documents(root):
        fenced=False
        for number,line in enumerate(path.read_text(encoding='utf-8-sig').splitlines(),1):
            if line.lstrip().startswith(('```','~~~')):fenced=not fenced
            if fenced:continue
            for match in re.finditer(r'!?\[[^\]]*\]\(([^)]+)\)',line):
                target=match[1].strip().split(' "',1)[0].strip('<>')
                if urlsplit(target).scheme or target.startswith('//'):continue
                name,_,anchor=unquote(target).partition('#')
                dest=(root/name.lstrip('/')) if name.startswith('/') else (path.parent/name if name else path)
                if not dest.exists():errors.append(f'{path.relative_to(root).as_posix()}:{number}: missing {target}')
                elif anchor and dest.suffix=='.md' and anchor not in headings(dest.read_text(encoding='utf-8-sig')):
                    errors.append(f'{path.relative_to(root).as_posix()}:{number}: missing heading {target}')
    return errors


def entry_points(root=ROOT):
    # Check configured launch targets without opening a GUI or starting a service.
    text=(root/'pyproject.toml').read_text(encoding='utf-8')
    errors=[]
    for module,fn in re.findall(r'"(crucible_[\w.]+):(\w+)"',text):
        path=root/'src'/Path(*module.split('.')).with_suffix('.py')
        if not path.is_file() or fn not in {n.name for n in ast.parse(path.read_text(encoding='utf-8')).body if isinstance(n,(ast.FunctionDef,ast.AsyncFunctionDef))}:
            errors.append(f'Invalid configured entry point: {module}:{fn}')
    return errors


def source_checks(root=ROOT):
    paths=[]
    for folder in ('src','scripts','tests'):
        paths+=list((root/folder).rglob('*.py'))
    paths+=list(root.glob('run_*.py'))+list((root/'design/cards').glob('*.py'))
    errors=[]
    for path in paths:
        try:ast.parse(path.read_text(encoding='utf-8-sig'),filename=str(path))
        except (SyntaxError,UnicodeError) as exc:errors.append(f'{path.relative_to(root).as_posix()}: {exc}')
    return len(paths),errors


def version_checks(root=ROOT):
    def assignments(path):
        return {n.targets[0].id:ast.literal_eval(n.value) for n in ast.parse((root/path).read_text(encoding='utf-8')).body
                if isinstance(n,ast.Assign) and len(n.targets)==1 and isinstance(n.targets[0],ast.Name) and isinstance(n.value,(ast.Constant,ast.Dict))}
    coverage=assignments('src/crucible_core/coverage.py')['MATCH_COVERAGE']['version']
    save=assignments('src/crucible_play/persistence.py')
    state=(root/'docs/PROJECT_STATE.md').read_text(encoding='utf-8')
    schema=(root/'docs/SAVE_FORMAT.md').read_text(encoding='utf-8')
    errors=[]
    if f'coverage.py v{coverage}' not in state:errors.append('PROJECT_STATE.md coverage version differs from code')
    if f'save schema v{save["VERSION"]}' not in state:errors.append('PROJECT_STATE.md save schema differs from code')
    if f'Schema v{save["VERSION"]} / gameplay compatibility {save["COMPATIBILITY_VERSION"]}' not in schema:errors.append('SAVE_FORMAT.md version differs from code')
    return {'coverage':coverage,'save_schema':save['VERSION'],'compatibility':save['COMPATIBILITY_VERSION']},errors


def render_index(root=ROOT):
    lines=['# Documentation index','','Generated by `python scripts/audit_docs.py --write-index`. Edit the role registry or source documents, then regenerate.','',
        'Start with PROJECT_STATE.md and AI_HANDOFF.md. Product decisions and rules have separate canonical owners; plans and past experiment counts do not describe current implementation. External reference corpora are inventoried, not adopted or revalidated here.','',
        '| Document | Role | Read for |','| --- | --- | --- |']
    paths={p.relative_to(root).as_posix() for p in documents(root)}|{'docs/DOCUMENTATION_INDEX.md'}
    for path in sorted(paths):
        kind,purpose=role(path);relative=path[5:] if path.startswith('docs/') else '../'+path
        lines.append(f'| [{path}]({relative}) | {kind} | {purpose} |')
    lines+=['','## Scope','',
        'All authored Markdown and reference intake READMEs are included above. Large copied rules/card databases, binaries, artwork and generated SVGs are not continuity instructions. Their presence does not make foreign cards executable.',
        'Historical experiment notes retain their recorded test counts and source versions. Generated tables retain their named input seeds. Consult PROJECT_STATE.md and the implementation coverage manifest for the current checkpoint.','']
    return '\n'.join(lines)


def make_bundle(root=ROOT):
    # Documentation only: deliberately excludes active art/editor work, private
    # saves, raw studies, reference corpora and historical interview transcripts.
    paths=[p for p in documents(root) if not p.relative_to(root).as_posix().startswith('references/') and p.relative_to(root).as_posix() not in HISTORY]
    paths+=[root/'design/packages/discard_draw.json']
    paths=[p for p in paths if p.is_file()]
    commit=subprocess.check_output(['git','rev-parse','HEAD'],cwd=root,text=True).strip()
    branch=subprocess.check_output(['git','branch','--show-current'],cwd=root,text=True).strip()
    data={p.relative_to(root).as_posix():p.read_bytes() for p in paths}
    manifest={'kind':'documentation-only','commit':commit,'branch':branch,
        'snapshot':'working-tree documentation; per-file hashes define contents',
        'files':{n:hashlib.sha256(b).hexdigest() for n,b in sorted(data.items())},
        'excluded':['source checkout (clone the named Git revision)','private saves','uncommitted card studio/art/template work','third-party reference corpora','historical interview transcripts']}
    out=root/'dist/Crucible-Documentation-Handoff.zip';out.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(out,'w',zipfile.ZIP_DEFLATED) as archive:
        for name,content in sorted(data.items()):archive.writestr(name,content)
        archive.writestr('handoff-manifest.json',json.dumps(manifest,indent=2))
    return out,len(data)


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--write-index',action='store_true');parser.add_argument('--bundle',action='store_true')
    args=parser.parse_args(argv)
    if args.write_index:(ROOT/'docs/DOCUMENTATION_INDEX.md').write_text(render_index(),encoding='utf-8')
    syntax_count,syntax_errors=source_checks()
    versions,version_errors=version_checks()
    errors=broken_links()+entry_points()+syntax_errors+version_errors
    count=len((ROOT/'docs/PROJECT_STATE.md').read_text(encoding='utf-8').splitlines())
    if count>=50:errors.append('PROJECT_STATE.md must remain under 50 lines')
    print(json.dumps({'authored_and_intake_documents':len(documents()),'python_sources_parsed':syntax_count,'versions':versions,'project_state_lines':count,'errors':errors},indent=2))
    if errors:return 2
    if args.bundle:
        path,n=make_bundle();print(f'Packaged {n} documentation/data files: {path}')
    return 0


if __name__=='__main__':raise SystemExit(main())
